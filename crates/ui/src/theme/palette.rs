//! A theme's primitives, the `--p-*` block of themes.css. Colours are `0xrrggbb`.

use super::ThemeVariant;

/// Ramps read by role: bg-0 is furthest back, bg-6 closest; fg-0 is the strongest text, fg-5 the
/// quietest. An optional field is a twin the theme only declares where its author's hue needs one.
#[derive(Clone, Debug, PartialEq)]
pub struct Palette {
    pub variant: ThemeVariant,
    pub bg_0: u32,
    pub bg_1: u32,
    pub bg_2: u32,
    pub bg_3: u32,
    pub bg_4: u32,
    pub bg_5: u32,
    pub bg_6: u32,
    pub line_0: u32,
    pub line_1: u32,
    pub line_2: u32,
    pub line_3: u32,
    pub fg_0: u32,
    pub fg_1: u32,
    pub fg_2: u32,
    pub fg_3: u32,
    pub fg_4: u32,
    pub fg_5: u32,
    pub contrast: u32,
    pub contrast_ink: u32,
    pub accent: u32,
    pub accent_bright: u32,
    pub accent_ink: u32,
    pub info: u32,
    pub info_strong: u32,
    pub info_ink: u32,
    pub link: u32,
    pub success: u32,
    pub danger: u32,
    pub warning: u32,
    pub alert: u32,
    pub alert_ink: u32,
    pub pr_merged: u32,
    pub on_hue: u32,
    pub syntax_comment: u32,
    pub syntax_string: u32,
    pub syntax_punctuation: u32,
    pub ansi_black: u32,
    pub ansi_red: u32,
    pub ansi_green: u32,
    pub ansi_yellow: u32,
    pub ansi_blue: u32,
    pub ansi_magenta: u32,
    pub ansi_cyan: u32,
    pub ansi_white: u32,
    pub ansi_bright_black: u32,
    pub ansi_bright_red: u32,
    pub ansi_bright_green: u32,
    pub ansi_bright_yellow: u32,
    pub ansi_bright_blue: u32,
    pub ansi_bright_magenta: u32,
    pub ansi_bright_cyan: u32,
    pub ansi_bright_white: u32,
    pub row_hover: Option<u32>,
    pub row_selected: Option<u32>,
    pub accent_text: Option<u32>,
    pub accent_hover: Option<u32>,
    pub info_text: Option<u32>,
    pub link_text: Option<u32>,
    pub success_text: Option<u32>,
    pub danger_text: Option<u32>,
    pub danger_ink: Option<u32>,
    pub warning_text: Option<u32>,
    pub syntax_keyword: Option<u32>,
    pub syntax_function: Option<u32>,
    pub syntax_type: Option<u32>,
    pub syntax_number: Option<u32>,
    pub syntax_constant: Option<u32>,
    pub syntax_tag: Option<u32>,
    pub syntax_attribute: Option<u32>,
    /// The shadow colour's channels, which every shadow thins.
    pub shadow: [u8; 3],
    pub scrim: [u8; 3],
    /// Holds shadows to one weight across grounds of different lightness.
    pub shadow_scale: f32,
    /// The weight of the hover wash, heavier on a light ground.
    pub wash_alpha: f32,
    pub disabled_opacity: f32,
}
