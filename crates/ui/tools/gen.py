#!/usr/bin/env python3
"""Generates act_ui's data files from the Electron app's sources.

    python3 -I crates/ui/tools/gen.py <path to ai-coding-tool>

Writes:
  crates/ui/src/theme/palettes.rs   every theme block in src/renderer/themes.css
  assets/icons/*.svg                every react-icons glyph the renderer imports
  crates/ui/src/icon_names.rs       the IconName enum over those files
  crates/ui/src/embedded.rs         the table of files the AssetSource serves
"""
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
UI = os.path.join(ROOT, "crates", "ui")
ASSETS = os.path.join(ROOT, "assets")

REQUIRED = [
    "bg-0", "bg-1", "bg-2", "bg-3", "bg-4", "bg-5", "bg-6",
    "line-0", "line-1", "line-2", "line-3",
    "fg-0", "fg-1", "fg-2", "fg-3", "fg-4", "fg-5",
    "contrast", "contrast-ink",
    "accent", "accent-bright", "accent-ink",
    "info", "info-strong", "info-ink", "link",
    "success", "danger", "warning", "alert", "alert-ink", "pr-merged", "on-hue",
    "syntax-comment", "syntax-string", "syntax-punctuation",
    "ansi-black", "ansi-red", "ansi-green", "ansi-yellow", "ansi-blue", "ansi-magenta", "ansi-cyan", "ansi-white",
    "ansi-bright-black", "ansi-bright-red", "ansi-bright-green", "ansi-bright-yellow", "ansi-bright-blue",
    "ansi-bright-magenta", "ansi-bright-cyan", "ansi-bright-white",
]
OPTIONAL = [
    "row-hover", "row-selected",
    "accent-text", "accent-hover", "info-text", "link-text", "success-text", "danger-text", "danger-ink", "warning-text",
    "syntax-keyword", "syntax-function", "syntax-type", "syntax-number", "syntax-constant", "syntax-tag", "syntax-attribute",
]
TRIPLES = ["shadow", "scrim"]
NUMBERS = ["shadow-scale", "wash-alpha", "disabled-opacity"]


def field(name):
    return name.replace("-", "_")


def hex_literal(value):
    value = value.strip().lstrip("#")
    if len(value) == 3:
        value = "".join(ch * 2 for ch in value)
    assert len(value) == 6, value
    return "0x" + value.lower()


def parse_themes(css):
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    themes = {}
    order = []
    for selectors, body in re.findall(r"([^{}]+)\{([^{}]*)\}", css):
        ids = re.findall(r'\[data-theme="([^"]+)"\]', selectors)
        for theme_id in ids:
            if theme_id not in themes:
                themes[theme_id] = {}
                order.append(theme_id)
            for name, value in re.findall(r"(--p-[a-z0-9-]+|color-scheme)\s*:\s*([^;]+);", body):
                themes[theme_id][name.replace("--p-", "")] = value.strip()
    return order, themes


def gen_palettes(app):
    with open(os.path.join(app, "src", "renderer", "themes.css")) as f:
        order, themes = parse_themes(f.read())
    out = ["// Generated by crates/ui/tools/gen.py from src/renderer/themes.css. Do not edit.", "",
           "use super::palette::Palette;", "use super::ThemeVariant;", ""]
    out.append("pub(crate) fn palette(id: &str) -> Option<Palette> {")
    out.append("    Some(match id {")
    for theme_id in order:
        values = themes[theme_id]
        out.append(f'        "{theme_id}" => Palette {{')
        variant = "Dark" if values["color-scheme"] == "dark" else "Light"
        out.append(f"            variant: ThemeVariant::{variant},")
        for name in REQUIRED:
            out.append(f"            {field(name)}: {hex_literal(values[name])},")
        for name in OPTIONAL:
            if name in values:
                out.append(f"            {field(name)}: Some({hex_literal(values[name])}),")
            else:
                out.append(f"            {field(name)}: None,")
        for name in TRIPLES:
            r, g, b = values[name].split()
            out.append(f"            {field(name)}: [{r}, {g}, {b}],")
        for name in NUMBERS:
            number = values[name]
            if "." not in number:
                number += ".0"
            out.append(f"            {field(name)}: {number},")
        out.append("        },")
    out.append("        _ => return None,")
    out.append("    })")
    out.append("}")
    with open(os.path.join(UI, "src", "theme", "palettes.rs"), "w") as f:
        f.write("\n".join(out) + "\n")
    return order


ICON_SETS = {"lu": "Lu", "bs": "Bs", "si": "Si"}


def camel_to_kebab(name):
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "-", name).lower()


def used_icons(app):
    names = set()
    pattern = re.compile(r"import\s*\{([^}]*)\}\s*from\s*\"react-icons/(lu|bs|si)\"")
    for base, _, files in os.walk(os.path.join(app, "src")):
        for file in files:
            if not file.endswith((".ts", ".tsx")):
                continue
            with open(os.path.join(base, file)) as f:
                text = f.read()
            for group, _ in pattern.findall(text):
                for part in group.split(","):
                    part = part.strip()
                    if part:
                        names.add(part.split(" as ")[0].strip())
    return sorted(names)


def svg_attr(name):
    special = {"className": "class", "viewBox": "viewBox"}
    if name in special:
        return special[name]
    return re.sub(r"(?<=[a-z])(?=[A-Z])", "-", name).lower()


def render_node(node):
    attrs = "".join(f' {svg_attr(k)}="{v}"' for k, v in node["attr"].items())
    children = "".join(render_node(child) for child in node.get("child", []))
    if node["tag"] == "svg":
        attrs = ' xmlns="http://www.w3.org/2000/svg"' + attrs
    if children:
        return f"<{node['tag']}{attrs}>{children}</{node['tag']}>"
    return f"<{node['tag']}{attrs}/>"


# Glyphs the stylesheets draw with borders rather than an icon font.
CUSTOM_ICONS = {
    # .list-heading-chevron: a 7px box's right and bottom edges, turned 45 degrees.
    # .btn-spinner: a 12px ring, 2px thick, with its right quarter clear.
    "SpinnerRing": '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 12 12" fill="none" stroke="currentColor" stroke-width="2"><path d="M9.536 9.536A5 5 0 1 1 9.536 2.464"/></svg>',
    "HeadingChevron": '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 12 12" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="square"><path d="M2.1 3.9 6 7.8 9.9 3.9"/></svg>',
}


def gen_icons(app):
    names = used_icons(app)
    sources = {}
    for folder in ICON_SETS:
        with open(os.path.join(app, "node_modules", "react-icons", folder, "index.js")) as f:
            sources[folder] = f.read()
    variants = []
    for name in names:
        prefix = name[:2]
        folder = {v: k for k, v in ICON_SETS.items()}[prefix]
        match = re.search(r"function " + re.escape(name) + r" \(props\) \{\s*return GenIcon\((\{.*?\})\)\(props\);", sources[folder])
        assert match, name
        tree = json.loads(match.group(1))
        variant = name[2:]
        file = camel_to_kebab(variant)
        with open(os.path.join(ASSETS, "icons", file + ".svg"), "w") as f:
            f.write(render_node(tree) + "\n")
        variants.append((variant, file, name))
    for variant, svg in CUSTOM_ICONS.items():
        file = camel_to_kebab(variant)
        with open(os.path.join(ASSETS, "icons", file + ".svg"), "w") as f:
            f.write(svg + "\n")
        variants.append((variant, file, "custom"))
    out = ["// Generated by crates/ui/tools/gen.py from the react-icons the renderer imports. Do not edit.", "",
           "/// Every glyph the app draws: Lucide, plus the three brand marks.",
           "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]", "pub enum IconName {"]
    for variant, _, original in variants:
        out.append(f"    /// `{original}`")
        out.append(f"    {variant},")
    out.append("}")
    out.append("")
    out.append("impl IconName {")
    out.append("    pub const ALL: &'static [IconName] = &[")
    for variant, _, _ in variants:
        out.append(f"        IconName::{variant},")
    out.append("    ];")
    out.append("")
    out.append("    /// The asset path the icon's SVG is served at.")
    out.append("    pub fn path(self) -> &'static str {")
    out.append("        match self {")
    for variant, file, _ in variants:
        out.append(f'            IconName::{variant} => "icons/{file}.svg",')
    out.append("        }")
    out.append("    }")
    out.append("}")
    with open(os.path.join(UI, "src", "icon_names.rs"), "w") as f:
        f.write("\n".join(out) + "\n")


def gen_embedded():
    files = []
    for base, _, names in os.walk(ASSETS):
        for name in names:
            if name.startswith("."):
                continue
            path = os.path.relpath(os.path.join(base, name), ASSETS)
            files.append(path.replace(os.sep, "/"))
    files.sort()
    out = ["// Generated by crates/ui/tools/gen.py from the assets folder. Do not edit.", "",
           "pub(crate) static FILES: &[(&str, &[u8])] = &["]
    for path in files:
        out.append(f'    ("{path}", include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), "/../../assets/{path}"))),')
    out.append("];")
    with open(os.path.join(UI, "src", "embedded.rs"), "w") as f:
        f.write("\n".join(out) + "\n")


def main():
    app = sys.argv[1]
    os.makedirs(os.path.join(ASSETS, "icons"), exist_ok=True)
    os.makedirs(os.path.join(UI, "src", "theme"), exist_ok=True)
    order = gen_palettes(app)
    gen_icons(app)
    gen_embedded()
    print(f"{len(order)} themes")


if __name__ == "__main__":
    main()
